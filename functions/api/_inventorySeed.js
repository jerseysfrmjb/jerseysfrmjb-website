const SIZE_ORDER = ["S", "M", "L", "XL", "2XL", "3XL", "4XL"];

function parseSizeStock(value) {
  try {
    const parsed = JSON.parse(value || "{}");
    return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? parsed : {};
  } catch {
    return {};
  }
}

function totalSizeStock(sizes) {
  return SIZE_ORDER.reduce((total, size) => total + Math.max(0, Math.floor(Number(sizes[size] || 0))), 0);
}

function normalizeSizeToken(value) {
  const text = String(value || "").trim().toUpperCase();
  if (text === "SMALL") return "S";
  if (text === "MEDIUM") return "M";
  if (text === "LARGE") return "L";
  if (text === "EXTRA LARGE") return "XL";
  return SIZE_ORDER.includes(text) ? text : "";
}

function hydrateLegacySizeStock(sizes, sizeLabel, quantity) {
  if (totalSizeStock(sizes) > 0) return sizes;
  const total = Math.max(0, Math.floor(Number(quantity || 0)));
  if (!total) return sizes;
  const labels = String(sizeLabel || "").split(",");
  const normalized = labels.map(normalizeSizeToken).filter(Boolean);
  if (normalized.length === 1) {
    sizes[normalized[0]] = total;
  }
  return sizes;
}

function sizeLabelFromStock(sizes, fallback = "") {
  const availableSizes = SIZE_ORDER.filter(size => Math.max(0, Math.floor(Number(sizes[size] || 0))) > 0);
  return availableSizes.length ? availableSizes.join(", ") : fallback;
}

async function applyOneTimeRestock(env, key, lines) {
  const existing = await env.DB.prepare("SELECT value FROM site_settings WHERE key = ?").bind(key).first();
  if (existing?.value === "applied") return;

  for (const line of lines) {
    const row = await env.DB.prepare("SELECT id, size, sizes_json, quantity FROM inventory WHERE id = ?").bind(line.id).first();
    if (!row) continue;

    const sizes = hydrateLegacySizeStock(parseSizeStock(row.sizes_json), row.size, row.quantity);
    const addQuantity = Math.max(0, Math.floor(Number(line.quantity || 0)));
    sizes[line.size] = Math.max(0, Math.floor(Number(sizes[line.size] || 0))) + addQuantity;
    const total = totalSizeStock(sizes);
    const label = sizeLabelFromStock(sizes, row.size || "");

    await env.DB.prepare(
      "UPDATE inventory SET sizes_json = ?, size = ?, quantity = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?"
    ).bind(JSON.stringify(sizes), label, total, line.id).run();
  }

  await env.DB.prepare(`INSERT INTO site_settings (key, value, updated_at)
    VALUES (?, 'applied', CURRENT_TIMESTAMP)
    ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = CURRENT_TIMESTAMP`).bind(key).run();
  await env.DB.prepare(`INSERT INTO site_settings (key, value, updated_at)
    VALUES ('inventory_updated_at', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
    ON CONFLICT(key) DO UPDATE SET value = CURRENT_TIMESTAMP, updated_at = CURRENT_TIMESTAMP`).run();
}

